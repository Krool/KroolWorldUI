using System;
using System.IO;
using System.Linq;
using System.Runtime.CompilerServices;
using System.Runtime.Loader;
using System.Text;
using BepInEx.Configuration;
using KroolWorldUI;

// Rewrites the block between the settings markers in README.md from Plugin.BindAll, so the docs
// list exactly the settings, defaults, ranges and descriptions the F7 window shows.
// Usage: SettingsDoc <README.md> <valheim_Data\Managed>

if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: SettingsDoc <README.md> <valheim_Data\\Managed>");
    return 2;
}

// The plugin references Unity and game assemblies that are not shipped with this tool; load them
// from the game install. Registered before anything touches a plugin type (see Generate).
string managed = args[1];
AssemblyLoadContext.Default.Resolving += (ctx, name) =>
{
    string path = Path.Combine(managed, name.Name + ".dll");
    return File.Exists(path) ? ctx.LoadFromAssemblyPath(path) : null;
};
return SettingsDoc.Generate(args[0]);

internal static class SettingsDoc
{
    private const string Begin = "<!-- settings:begin (generated by tools/SettingsDoc; edit the config.Bind descriptions instead) -->";
    private const string End = "<!-- settings:end -->";

    // Separate method so the JIT resolves plugin and Unity types only after the resolver is set.
    [MethodImpl(MethodImplOptions.NoInlining)]
    internal static int Generate(string readmePath)
    {
        string temp = Path.Combine(Path.GetTempPath(), $"kwui-settings-{Guid.NewGuid():N}.cfg");
        try
        {
            var config = new ConfigFile(temp, false);
            Plugin.BindAll(config);

            var md = new StringBuilder();
            md.Append(Begin).Append('\n');
            foreach (var section in config.Keys.GroupBy(k => k.Section))
            {
                var entries = section.Select(d => config[d]).Where(e => !ConfigText.IsHidden(e)).ToList();
                if (entries.Count == 0) continue;
                md.Append($"\n**{section.Key}**\n\n");
                md.Append("| Setting | Default | Range or choices | What it does |\n");
                md.Append("|---|---|---|---|\n");
                foreach (var e in entries)
                {
                    string def = ConfigText.Value(e.DefaultValue);
                    if (e.SettingType == typeof(UnityEngine.Color)) def = $"`{def}`";
                    md.Append($"| {ConfigText.Pretty(e.Definition.Key)} | {def} | {Cell(ConfigText.Options(e))} | {Cell(e.Description?.Description)} |\n");
                }
            }
            md.Append('\n').Append(End);

            string readme = File.ReadAllText(readmePath);
            int a = readme.IndexOf("<!-- settings:begin", StringComparison.Ordinal);
            int b = readme.IndexOf(End, StringComparison.Ordinal);
            if (a < 0 || b < a)
            {
                Console.Error.WriteLine($"{readmePath}: settings markers not found");
                return 1;
            }
            string updated = readme.Substring(0, a) + md + readme.Substring(b + End.Length);
            if (updated == readme)
            {
                Console.WriteLine("README settings tables already current.");
                return 0;
            }
            File.WriteAllText(readmePath, updated, new UTF8Encoding(false));
            Console.WriteLine("README settings tables updated.");
            return 0;
        }
        finally
        {
            File.Delete(temp);
        }
    }

    private static string Cell(string text) => (text ?? "").Replace("|", "\\|").Replace("\r", "").Replace("\n", " ");
}
